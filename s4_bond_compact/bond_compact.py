def 构造语料() -> List[Dict[str, str]]:
    """组装50条模拟信息为消息列表（对应“某交易日债市波动信息流”）。"""
    messages: List[Dict[str, str]] = []
    for seed in SEEDS:
        messages.append({"role": "user", "content": f"[{seed['编号']}·{seed['类型']}·{seed['日期']}] {seed['内容']}（来源：{seed['来源']}）"})
    for ext_id, ext_type, ext_date, ext_content, seed_id in EXTENSIONS:
        messages.append({"role": "user", "content": f"[{ext_id}·{ext_type}·{ext_date}] {ext_content}（依据种子：{seed_id}）"})
    return messages


def 解析条目(message: Dict[str, str]) -> Dict[str, str]:
    """从消息文本中解析编号、类型、日期与正文。"""
    header, _, body = message["content"].partition("]")
    header = header.lstrip("[")
    编号, 类型, 日期 = (header.split("·") + ["", "", ""])[:3]
    return {"编号": 编号, "类型": 类型, "日期": 日期, "正文": body.strip()}


def 相关性打分(正文: str) -> int:
    """命中债市核心议题关键词的次数即为相关性得分。"""
    return sum(1 for kw in RELEVANCE_KEYWORDS if kw in 正文)


def compact_context(messages: List[Dict[str, str]], budget: int) -> List[Dict[str, str]]:
    # 去粗取精、去伪存真、由此及彼、由表及里
    """三层过滤：权威性分层 → 相关性打分 → 去噪摘要，在预算内保留关键信息。"""
    entries = [解析条目(m) for m in messages]
    total_chars = sum(len(e["正文"]) for e in entries)

    # 第一层：权威性分层——按类型权重与相关性综合排序
    for e in entries:
        e["权威性"] = AUTHORITY_WEIGHT.get(e["类型"], 0)
        e["相关性"] = 相关性打分(e["正文"])
        e["是否扩展"] = 1 if "-扩" in e["编号"] else 0
    # 权威层级相同的情况下，种子原文恒优先于扩展语料，再比相关性
    ranked = sorted(entries, key=lambda e: (e["权威性"], -e["是否扩展"], e["相关性"]), reverse=True)

    # 第二层：相关性打分 + 同源去重——同一种子编号的扩展语料只保留权威最高的一条
    kept: List[Dict[str, str]] = []
    seen_sources = set()
    for e in ranked:
        seed_id = e["编号"].split("-")[0]
        if seed_id in seen_sources:
            continue  # 重复传闻/同源改写，剔除
        seen_sources.add(seed_id)
        kept.append(e)

    # 第三层：去噪摘要——在字符预算内填充，剔除情绪渲染类噪声
    # 把握主要矛盾——在信息过载中保持战略清醒与政治定力
    摘要行: List[str] = []
    used = 0
    剔除统计: Dict[str, int] = {}
    for e in kept:
        line = f"{e['编号']}（{e['类型']}·{e['日期']}）：{e['正文']}"
        if used + len(line) > budget:
            剔除统计[e["类型"]] = 剔除统计.get(e["类型"], 0) + 1
            continue
        if e["类型"] == "情绪帖":
            剔除统计["情绪帖（噪声）"] = 剔除统计.get("情绪帖（噪声）", 0) + 1
            continue  # 情绪渲染不进入决策上下文
        摘要行.append(line)
        used += len(line)

    压缩后 = "\n".join(摘要行)
    print(f"[压缩对比] 压缩前：{len(entries)}条 / 约{total_chars}字符；"
          f"预算：{budget}字符；压缩后：{len(摘要行)}条 / 约{used}字符")
    if 剔除统计:
        detail = "、".join(f"{k}{v}条" for k, v in 剔除统计.items())
        print(f"[去噪剔除] {detail}")
    return [{"role": "user", "content": "[压缩摘要]\n" + 压缩后}]


